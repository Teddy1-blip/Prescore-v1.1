export function compareWithLegacy(classification: TransactionClassification, legacyCategory?: string): TransactionClassification {
  if (!legacyCategory) return classification;
  return {
    ...classification,
    legacyCategory,
    legacyDiff: !LEGACY_EQUIVALENTS[classification.primaryCategory].includes(legacyCategory),
  };
}
