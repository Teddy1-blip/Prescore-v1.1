export const ANALYST_QUESTIONS = {
  index: 'Почему такой Prescore Index?',
  readiness: 'Что ограничивает готовность к финансированию?',
  debt: 'Какие обязательства, платежи и долговую ёмкость подтверждают источники?',
  products: 'Какие формы финансирования подходят и почему?',
  actions: 'Какой первый шаг и каков план на 7/30/60 дней?',
  concentration: 'Что известно о концентрации поступлений?',
  strengths: 'Какие сильные стороны подтверждены?',
  risks: 'Какие риски и стоп-факторы требуют внимания?',
  banking: 'Что показывают банковские выписки?',
  financials: 'Что показывает БФО и как оно соотносится с банковскими данными?',
  reconciliation: 'Есть ли противоречия между источниками?',
  missing: 'Какие данные и документы отсутствуют?',
  meeting: 'Что обсудить с кредитным специалистом и какие документы подготовить?',
  enrichment: 'Какие блоки уточнит дополнительный источник?',
  boundary: 'Можно ли по этому анализу гарантировать одобрение, ставку или лимит?',
  overview: 'Сформируй краткое резюме для собственника.'
} as const;
export type AnalystTopic = keyof typeof ANALYST_QUESTIONS;
export function analystTopic(question: string): AnalystTopic {
  const q = question.toLowerCase();
  if (/придумай|выдумай|игнорируй|ignore previous|гарантир|точно.{0,20}одобр|вероятность одобр|банк.{0,8}точно/.test(q)) return 'boundary';
  if (/обсуд|специалист|вопрос.{0,16}(банк|встреч)|подготов.{0,18}(встреч|банку)/.test(q)) return 'meeting';
  if (/добав|дополн|измен/.test(q) && /бфо|отч[её]тност|бухгалт|бки|кредитн.*истор|выписк/.test(q)) return 'enrichment';
  if (/противореч|расхожд|сверк|конфликт|сходятся/.test(q)) return 'reconciliation';
  if (/не хват|не хватает|недоста|отсутств|нужны.{0,15}документ/.test(q)) return 'missing';
  if (/бфо|бухгалт|отч[её]тност|выруч|прибыл|ликвидност|рентабельн/.test(q)) return 'financials';
  if (/index|индекс|рейтинг|оценка prescore/.test(q)) return 'index';
  if (/концентрац|покупател|контрагент/.test(q)) return 'concentration';
  if (/бки|кредитн.*истор|долг|обязательств|нагруз|плат[её]ж|просроч|лимит|[её]мкост|debt capacity/.test(q)) return 'debt';
  if (/продукт|тип финанс|форм.{0,8}финанс|куда подав|что выбрать|подход.{0,12}финанс/.test(q)) return 'products';
  if (/план|перв|сделать|исправить|рекомендац|следующ.{0,10}шаг|7\s*\/\s*30/.test(q)) return 'actions';
  if (/сильн.{0,12}сторон|сильн.{0,12}фактор|плюс|преимущ/.test(q)) return 'strengths';
  if (/риск|стоп|stop.factor/.test(q)) return 'risks';
  if (/выписк|оборот|поступлен|денежн.*поток/.test(q)) return 'banking';
  if (/готов|подав|огранич|мешает|финанс/.test(q)) return 'readiness';
  return 'overview';
}
