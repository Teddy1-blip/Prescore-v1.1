import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {extractDocumentText,extractLegacyXlsSheets} from '../../lib/credit-engine/server/document-extraction.ts';
import {selectAccountingSheet} from '../../lib/workspace/accounting-xlsx-scope.ts';
import {parseLedger} from '../../lib/workspace/ledger-import.ts';
const name='tests/fixtures/synthetic-ledger.xls';
const bytes=await readFile(name);
const text=await extractDocumentText(name,bytes);
const [line]=parseLedger(text,'7707083893','COUNTERPARTIES');
assert.equal(line.asOf,'2025-12-31');
assert.equal(line.contract,'Д-42');
assert.equal(line.debit,1850.75);
assert.equal(line.credit,null);
const sheets=await extractLegacyXlsSheets(bytes);
assert.ok(sheets.length>=1);
const selected=selectAccountingSheet(sheets,'OSV');
assert.ok(selected.rows.length>1);
assert.equal(selected.rows.length,selected.rowNumbers.length);
assert.ok(selected.rowNumbers.every((v,i)=>Number.isSafeInteger(v)&&v>0&&(i===0||v>selected.rowNumbers[i-1])));
const structuredText=selected.rows.map(row=>row.join('\t')).join('\n');
const [structuredLine]=parseLedger(structuredText,'7707083893','COUNTERPARTIES');
assert.equal(structuredLine.debit,line.debit);
assert.equal(structuredLine.asOf,line.asOf);
assert.equal(structuredLine.contract,line.contract);
assert.throws(()=>selectAccountingSheet([selected,{...selected,sheet:'another-data-sheet'}],'OSV'),/ACCOUNTING_XLSX_MULTIPLE_SOURCE_SHEETS/);
await assert.rejects(extractDocumentText('invalid.xls',bytes.subarray(0,50)));
await assert.rejects(extractLegacyXlsSheets(bytes.subarray(0,50)));
console.log('PASS legacy XLS • single-sheet scope, physical row map, values and malformed input');
